-- ---------------------------------------------------------------- orders
create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated always as identity (start with 1001) unique,
  customer_id uuid not null references public.profiles (id) on delete restrict,
  driver_id uuid references public.drivers (id) on delete set null,
  service_id smallint not null references public.services (id),
  -- snapshot of the service at order time (filled by trigger)
  service_code text not null,
  service_name_ar text not null,
  service_name_en text not null,
  quantity smallint not null default 1 check (quantity between 1 and 10),
  unit_price numeric(10, 2) not null,
  delivery_fee numeric(10, 2) not null default 0,
  total_price numeric(10, 2) not null,
  payment_method public.payment_method not null default 'cash',
  status public.order_status not null default 'pending',
  delivery_lat double precision not null,
  delivery_lng double precision not null,
  delivery_address text,
  notes text check (char_length(notes) <= 300),
  city_id smallint references public.cities (id),
  rating smallint check (rating between 1 and 5),
  rating_comment text check (char_length(rating_comment) <= 300),
  cancel_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  accepted_at timestamptz,
  on_the_way_at timestamptz,
  delivered_at timestamptz,
  cancelled_at timestamptz
);

create index orders_customer_idx on public.orders (customer_id, created_at desc);
create index orders_driver_idx on public.orders (driver_id, created_at desc);
create index orders_open_idx on public.orders (status) where status in ('pending', 'accepted', 'on_the_way');
-- A customer can have only one open order at a time.
create unique index orders_one_open_per_customer on public.orders (customer_id)
  where status in ('pending', 'accepted', 'on_the_way');

alter table public.drivers
  add constraint drivers_current_order_fk foreign key (current_order_id)
  references public.orders (id) on delete set null;

create trigger orders_updated_at before update on public.orders
  for each row execute function public.set_updated_at();

-- Prices and status are always decided by the server, never by the client.
create or replace function public.prepare_new_order()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  s public.services;
  fee numeric(10, 2);
begin
  select * into s from public.services where id = new.service_id and is_active;
  if not found then
    raise exception 'SERVICE_UNAVAILABLE';
  end if;
  select delivery_fee into fee from public.app_config where id;
  fee := coalesce(fee, 0);

  new.service_code := s.code;
  new.service_name_ar := s.name_ar;
  new.service_name_en := s.name_en;
  new.unit_price := s.price;
  new.delivery_fee := fee;
  new.total_price := s.price * new.quantity + fee;
  new.status := 'pending';
  new.driver_id := null;
  new.rating := null;
  new.rating_comment := null;
  new.cancel_reason := null;
  new.created_at := now();
  new.updated_at := now();
  new.accepted_at := null;
  new.on_the_way_at := null;
  new.delivered_at := null;
  new.cancelled_at := null;
  if new.city_id is null then
    select city_id into new.city_id from public.profiles where id = new.customer_id;
  end if;
  return new;
end $$;

create trigger orders_prepare before insert on public.orders
  for each row execute function public.prepare_new_order();

-- ---------------------------------------------------------------- order events (audit trail)
create table public.order_events (
  id bigint generated always as identity primary key,
  order_id uuid not null references public.orders (id) on delete cascade,
  status public.order_status not null,
  actor_id uuid,
  created_at timestamptz not null default now()
);
create index order_events_order_idx on public.order_events (order_id, created_at);

create or replace function public.log_order_event()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'INSERT' or new.status is distinct from old.status then
    insert into public.order_events (order_id, status, actor_id)
    values (new.id, new.status, auth.uid());
  end if;
  return new;
end $$;

create trigger orders_log_event after insert or update of status on public.orders
  for each row execute function public.log_order_event();

-- ---------------------------------------------------------------- RLS helper functions
-- SECURITY DEFINER so policies can check other tables without recursion.
create or replace function public.is_active_customer()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'customer' and is_active
  );
$$;

create or replace function public.is_verified_driver()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.drivers d join public.profiles p on p.id = d.id
    where d.id = auth.uid() and d.is_verified and p.is_active
  );
$$;

create or replace function public.is_my_assigned_driver(p_driver_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.orders
    where customer_id = auth.uid() and driver_id = p_driver_id
      and status in ('accepted', 'on_the_way')
  );
$$;

create or replace function public.can_view_order(p_order_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.orders
    where id = p_order_id and (customer_id = auth.uid() or driver_id = auth.uid())
  );
$$;

