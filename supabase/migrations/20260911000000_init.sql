-- =============================================================================
-- ClickGas - initial schema (customer app now, driver app later)
--
-- Run once in Supabase Dashboard -> SQL Editor (or `supabase db push`).
--
-- Design:
--   * profiles  : one row per auth user (customer / driver / admin), created by
--                 a trigger on sign-up. Role is never taken from the client.
--   * drivers   : extra data + live location for driver accounts (driver app).
--   * orders    : prices are recomputed server-side on insert; status changes
--                 only through the RPC functions below (no direct UPDATE).
--   * order_events : audit trail of every status change.
--   * Row Level Security on every table; helper functions are SECURITY DEFINER
--     so policies never recurse into each other.
-- =============================================================================

