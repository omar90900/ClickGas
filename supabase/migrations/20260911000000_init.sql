-- Catalog: readable before sign-in (the sign-up screen lists cities).
create policy "cities are public" on public.cities
  for select to anon, authenticated using (is_active);
create policy "services are public" on public.services
  for select to anon, authenticated using (is_active);
create policy "config is public" on public.app_config
  for select to anon, authenticated using (true);

-- Profiles: each user sees and edits only their own record.
create policy "read own profile" on public.profiles
  for select to authenticated using (id = auth.uid());
create policy "update own profile" on public.profiles
  for update to authenticated using (id = auth.uid()) with check (id = auth.uid());
revoke insert, update, delete on public.profiles from anon, authenticated;
grant update (full_name, phone, city_id, avatar_url) on public.profiles to authenticated;

-- Drivers: customers see online verified distributors on the map and the
-- driver assigned to their open order; drivers manage their own row.
create policy "online drivers are visible" on public.drivers
  for select to authenticated using (is_online and is_verified);
create policy "assigned driver is visible" on public.drivers
  for select to authenticated using (public.is_my_assigned_driver(id));
create policy "driver reads self" on public.drivers
  for select to authenticated using (id = auth.uid());
create policy "driver updates self" on public.drivers
  for update to authenticated using (id = auth.uid()) with check (id = auth.uid());
revoke insert, update, delete on public.drivers from anon, authenticated;
grant update (is_online, lat, lng, heading, location_updated_at,
              vehicle_plate, vehicle_model, wallet_number) on public.drivers to authenticated;

-- Orders: customers create and read their own; drivers read pending orders
-- and the ones assigned to them. Every status change goes through an RPC.
create policy "customer reads own orders" on public.orders
  for select to authenticated using (customer_id = auth.uid());
create policy "driver reads assigned orders" on public.orders
  for select to authenticated using (driver_id = auth.uid());
create policy "verified drivers read pending orders" on public.orders
  for select to authenticated using (status = 'pending' and public.is_verified_driver());
create policy "customer creates order" on public.orders
  for insert to authenticated
  with check (customer_id = auth.uid() and public.is_active_customer());
revoke update, delete on public.orders from anon, authenticated;
revoke insert on public.orders from anon;

create policy "order parties read events" on public.order_events
  for select to authenticated using (public.can_view_order(order_id));
revoke insert, update, delete on public.order_events from anon, authenticated;

-- ---------------------------------------------------------------- RPC: auth helpers
-- Login by phone: returns the account email so the app can sign in with
-- email + password (Supabase phone login would require SMS).
create or replace function public.email_for_phone(p_phone text)
returns text language sql stable security definer set search_path = '' as $$
  select email from public.profiles where phone = p_phone and is_active limit 1;
$$;

create or replace function public.is_phone_registered(p_phone text)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles where phone = p_phone);
$$;

-- ---------------------------------------------------------------- RPC: customer actions
create or replace function public.cancel_order(p_order_id uuid, p_reason text default null)
returns public.orders language plpgsql security definer set search_path = '' as $$
declare
  o public.orders;
begin
  update public.orders
     set status = 'cancelled', cancelled_at = now(), cancel_reason = left(p_reason, 200)
   where id = p_order_id and customer_id = auth.uid() and status = 'pending'
  returning * into o;
  if not found then
    raise exception 'ORDER_NOT_CANCELLABLE';
  end if;
  return o;
end $$;

create or replace function public.rate_order(p_order_id uuid, p_rating smallint, p_comment text default null)
returns public.orders language plpgsql security definer set search_path = '' as $$
declare
  o public.orders;
begin
  if p_rating < 1 or p_rating > 5 then
    raise exception 'INVALID_RATING';
  end if;
  update public.orders
     set rating = p_rating, rating_comment = left(p_comment, 300)
   where id = p_order_id and customer_id = auth.uid()
     and status = 'delivered' and rating is null
  returning * into o;
  if not found then
    raise exception 'ORDER_NOT_RATEABLE';
  end if;
  if o.driver_id is not null then
    update public.drivers
       set rating_sum = rating_sum + p_rating, rating_count = rating_count + 1
     where id = o.driver_id;
  end if;
  return o;
end $$;

-- Driver card for the customer's open order (name + phone are private
-- otherwise, so they are exposed only through this function).
create or replace function public.get_order_driver(p_order_id uuid)
returns table (
  id uuid, full_name text, phone text, vehicle_plate text, vehicle_model text,
  rating_avg numeric, lat double precision, lng double precision, heading real
) language sql stable security definer set search_path = '' as $$
  select d.id, p.full_name, p.phone, d.vehicle_plate, d.vehicle_model,
         case when d.rating_count = 0 then 0
              else round(d.rating_sum::numeric / d.rating_count, 1) end,
         d.lat, d.lng, d.heading
    from public.orders o
    join public.drivers d on d.id = o.driver_id
    join public.profiles p on p.id = d.id
   where o.id = p_order_id and o.customer_id = auth.uid();
$$;

-- ---------------------------------------------------------------- RPC: driver actions (driver app)
create or replace function public.accept_order(p_order_id uuid)
returns public.orders language plpgsql security definer set search_path = '' as $$
declare
  o public.orders;
begin
  if not public.is_verified_driver() then
    raise exception 'NOT_A_VERIFIED_DRIVER';
  end if;
  if exists (select 1 from public.orders
             where driver_id = auth.uid() and status in ('accepted', 'on_the_way')) then
    raise exception 'DRIVER_BUSY';
  end if;
  update public.orders
     set status = 'accepted', driver_id = auth.uid(), accepted_at = now()
   where id = p_order_id and status = 'pending'
  returning * into o;
  if not found then
    raise exception 'ORDER_NOT_AVAILABLE';
  end if;
  update public.drivers set current_order_id = o.id where id = auth.uid();
  return o;
end $$;

create or replace function public.start_delivery(p_order_id uuid)
returns public.orders language plpgsql security definer set search_path = '' as $$
declare
  o public.orders;
begin
  update public.orders
     set status = 'on_the_way', on_the_way_at = now()
   where id = p_order_id and driver_id = auth.uid() and status = 'accepted'
  returning * into o;
  if not found then
    raise exception 'INVALID_TRANSITION';
  end if;
  return o;
end $$;

create or replace function public.complete_order(p_order_id uuid)
returns public.orders language plpgsql security definer set search_path = '' as $$
declare
  o public.orders;
begin
  update public.orders
     set status = 'delivered', delivered_at = now()
   where id = p_order_id and driver_id = auth.uid() and status in ('accepted', 'on_the_way')
  returning * into o;
  if not found then
    raise exception 'INVALID_TRANSITION';
  end if;
  update public.drivers set current_order_id = null where id = auth.uid();
  return o;
end $$;

