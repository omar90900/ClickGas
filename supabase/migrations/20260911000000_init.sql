-- ---------------------------------------------------------------- profiles
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  role public.user_role not null default 'customer',
  full_name text not null check (char_length(full_name) between 2 and 80),
  -- Jordanian mobile numbers in E.164: +9627[7|8|9]XXXXXXX
  phone text not null unique check (phone ~ '^\+9627[789][0-9]{7}$'),
  email text,
  city_id smallint references public.cities (id),
  avatar_url text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create trigger profiles_updated_at before update on public.profiles
  for each row execute function public.set_updated_at();

-- Sign-up creates the profile from the metadata sent by the app.
-- Everyone starts as a customer; drivers are promoted by an admin.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, full_name, phone, email, city_id, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    new.raw_user_meta_data ->> 'phone',
    new.email,
    nullif(new.raw_user_meta_data ->> 'city_id', '')::smallint,
    'customer'
  );
  return new;
end $$;

create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

